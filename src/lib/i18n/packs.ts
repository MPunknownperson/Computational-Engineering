/**
 * Site-wide language packs.
 *
 * Like an OS or game language pack, each pack is the complete set of words the
 * site can draw on in one language: interface and navigation strings, number
 * words, currency and unit names, topic vocabulary and grammatical connectors.
 * The voice engine combines these to understand commands, and the UI reads its
 * labels from the same resources. Adding a language means adding one pack;
 * there is no per-feature string table elsewhere.
 */

import type { Currency } from "@/lib/catalog";

export type PackId = "en" | "es" | "fr" | "de" | "zh";

/** Derived from the catalogue so a currency added there is automatically speakable. */
export type CurrencyCode = Currency;

/** Unit key: `${category}:${unitId}` using the ids of the unit converter. */
export type UnitKey = string;

export type TopicId =
  | "loan" | "tip" | "compound" | "quadratic" | "matrix" | "scientific" | "formula"
  | "inflation" | "gdp" | "bitcoin" | "crypto" | "currency" | "units";

export type UiKey =
  | "nav.home" | "nav.tools" | "nav.guides" | "nav.formulas" | "nav.finance" | "nav.currency" | "nav.assets" | "nav.economy"
  | "voice.heading" | "voice.speak" | "voice.stop" | "voice.cancel" | "voice.unavailableButton"
  | "voice.listening" | "voice.preparing" | "voice.waitingMic" | "voice.heard" | "voice.opening"
  | "voice.understoodAs" | "voice.retryHint"
  | "voice.open" | "voice.noMatch" | "voice.tryOne" | "voice.learned" | "voice.forget"
  | "voice.disclosureLocal" | "voice.disclosureCloud" | "voice.disclosureOnDeviceModel"
  | "voice.modelProvider" | "voice.modelFileProgress"
  | "voice.privacyLink" | "unavailable.noModel"
  | "unavailable.noApi" | "unavailable.region" | "unavailable.noLocal" | "unavailable.noCloud"
  | "mic.denied" | "mic.noDevice" | "mic.inUse" | "mic.insecure" | "mic.unsupported"
  | "speech.noSpeech" | "speech.network" | "speech.service" | "speech.language" | "speech.audio"
  | "speech.busy" | "speech.generic"
  | "topic.loan" | "topic.tip" | "topic.compound" | "topic.quadratic" | "topic.matrix"
  | "topic.scientific" | "topic.formula" | "topic.inflation" | "topic.gdp" | "topic.bitcoin"
  | "topic.crypto" | "topic.currency" | "topic.units"
  | "label.currency" | "label.units";

export interface NumberLexicon {
  /** Additive words: zero–nineteen, tens, and (where a language has them) whole hundreds. */
  values: Record<string, number>;
  /** Multipliers: hundred, thousand, million. */
  scales: Record<string, number>;
  /** Words that may sit between number words ("and", "y", "et", "und"). */
  joiners: string[];
}

export interface LanguagePack {
  id: PackId;
  name: string;
  nativeName: string;
  /** BCP 47 locales handed to the speech recogniser, best first. */
  speechLocales: string[];
  /** "space" languages match whole words; "none" (CJK) match substrings. */
  segmentation: "space" | "none";
  decimalSeparator: "." | ",";
  numbers: NumberLexicon | "cjk";
  /** Words that introduce the target ("to", "into", "a", "en", "in", "换成"). */
  toWords: string[];
  /** Verbs people say before a conversion; recognised but not required. */
  verbs: string[];
  currencies: Partial<Record<CurrencyCode, string[]>>;
  units: Record<UnitKey, string[]>;
  topics: Partial<Record<TopicId, string[]>>;
  /** Words that ask to run the previous command again. */
  repeat: string[];
  /** Default target when only one currency is spoken. */
  defaultCurrency: CurrencyCode;
  /** Economy used for indicator questions in this language. */
  defaultEconomy: string;
  examples: string[];
  ui: Record<UiKey, string>;
}

